/**
 * 跨层共享的硬性限额 —— 单一来源。
 *
 * 为什么值得单开一个文件：这些数字同时出现在**四个地方** ——
 * 后端的入参校验、数据库的 DEFAULT、planner 的计算窗口，以及前端的输入控件
 * （前端为了即时反馈会在浏览器里自己算一遍）。分开写的结果就是改一处漏三处，
 * 而表现非常隐蔽：界面允许填"提前 30 天"，服务端默默夹到 7 天，
 * 用户看到的和实际发生的不一致，且没有任何报错。
 *
 * 前端拿不到这个模块（它是 TS，而项目零构建、前端是单个 HTML），
 * 所以这些值通过 `/api/meta` 下发。`tests/ui.smoke.mjs` 会把服务端的值
 * 和前端实际用来约束输入的数字比对一遍，防止两边再次漂移。
 */

/**
 * Trakt 日历 `days` 参数的硬上限。
 *
 * ⚠️ 这**不是我们给用户的限额**，是 Trakt 服务端的事实：传更大的值不会报错，
 * 但也不会返回更多数据。所以它必须留着 —— `computeWindows` 的分片逻辑靠它
 * 决定每次请求几天，删掉会导致窗口被整体截断（靠前那几天静默消失）。
 *
 * 它也**刻意不下发给界面**：用户不需要知道这个数字，因为它不构成任何限制
 * （人为的偏移上限才需要告知）。本项目不设偏移上限。
 */
export const TRAKT_MAX_DAYS = 33

/**
 * 推送预览的**默认前视窗口**（天）。
 *
 * ⚠️ 它**只**管预览窗口，与规则无关：界面上给用户一个"只能看 N 天内"的框，
 * 只会让人以为更远的内容推不了，而实际上没有任何理由要限制它。
 */
export const DEFAULT_HORIZON_DAYS = 14

/** 推送预览的默认前视窗口（分钟）—— 由 DEFAULT_HORIZON_DAYS 推出，别单独写一个数 */
export const DEFAULT_HORIZON_MINUTES = DEFAULT_HORIZON_DAYS * 24 * 60

/**
 * 推送预览的默认**回看**窗口（天）。
 *
 * 与 `TICK_LOOKBACK_MINUTES` 的默认 2880 分钟（2 天）对齐：预览默认看回两天，
 * 正好覆盖"昨天/今天刚播的"—— 用户最常问的"怎么没通知我"就在这个范围里。
 */
export const DEFAULT_LOOKBACK_DAYS = 2

/**
 * 预览窗口**单侧**的天数上限（服务端兜底）。
 *
 * 为什么需要：Trakt 日历一次请求最多返回 `TRAKT_MAX_DAYS`(33) 天（传更大的值
 * 不报错，但也不会有更多数据）。预览允许"回看 7 天 + 前视 30 天"这种组合，
 * 跨度 38 天 > 33 ⇒ 必须**分片**多次拉，否则靠前的那几天直接消失且不报错。
 * 分片每次都消耗用户共享的 Trakt 配额，所以要有个上限：
 * 60 天 ⇒ 前后合计最多 4 片，够看一整季，又不会把配额打爆。
 *
 * ⚠️ **界面上不设这个上限**（用户想填多少填多少），钳制只在服务端做。
 */
export const MAX_PREVIEW_SPAN_DAYS = 60

/**
 * 账号数上限（管理页输入框的 max + 服务端校验共用）。
 *
 * 200 是按 Trakt API 配额反推的经验值：默认每人每 15 分钟重算一次计划
 * （`PLAN_REFRESH_MINUTES`），一次约 4~5 个 Trakt 请求 ⇒ 每人每 5 分钟约 1.5 个；
 * 1000 的配额留出余量后大致就是 200 人。
 *
 * 通过 `/api/admin/settings` 的 `maxUsersLimit` 下发给管理页 —— 输入框的 max
 * 与服务端校验同源，改这里不会两边漂移。
 */
export const MAX_USERS_LIMIT = 200

/** 规则名长度上限（界面 maxlength + 服务端校验共用） */
export const RULE_NAME_MAX_LENGTH = 60
